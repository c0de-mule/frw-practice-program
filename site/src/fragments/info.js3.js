const FP_TIER_NAMES = {"read":"Tier 1: Sensing the Direction","phrase":"Tier 2: Shaping the Phrase","twin":"Tier 3: Sophisticated Discernment"};
const FP_TIER_SHORT = {"read":"Tier 1","phrase":"Tier 2","twin":"Tier 3"};
let fpPos = 0;
let fpResults = new Array(FP_SCENARIOS.length).fill(null); // null | 'correct' | 'missed'
let fpPicked = new Array(FP_SCENARIOS.length).fill(-1);   // which option index they clicked

let fpOrigin = 'sample';   // 'sample' = the button under the sample; 'price' = the line under the pricing
function enterFoldedPreview(origin){
  fpOrigin = (origin === 'price') ? 'price' : 'sample';
  document.body.classList.add('preview-mode');
  fpPos = 0;
  fpResults = new Array(FP_SCENARIOS.length).fill(null);
  fpPicked = new Array(FP_SCENARIOS.length).fill(-1);
  // Reset button display in case they were hidden by a previous 'done' screen
  document.getElementById('fp-prev').style.display = '';
  document.getElementById('fp-next').style.display = '';
  document.getElementById('fp-sidebar').style.display = '';
  document.getElementById('fp-enroll').style.display = '';
  fpRender();
  window.scrollTo(0,0);
}

function exitFoldedPreviewTo(id){
  document.body.classList.remove('preview-mode');
  setTimeout(() => {
    const target = document.getElementById(id);
    if(target) target.scrollIntoView({behavior:'smooth', block:'start'});
  }, 50);
}

function exitFoldedPreview(){
  document.body.classList.remove('preview-mode');
  setTimeout(() => {
    /* Someone who came from the sample has not read the tiers or the price yet,
       so send them forward. Someone who came from the pricing line has read
       everything and went to the preview to settle one question — send them back
       to the decision, not backwards through the page. */
    const target = document.getElementById(fpOrigin === 'price' ? 'enroll' : 'tiers');
    if(target) target.scrollIntoView({behavior:'smooth', block:'start'});
  }, 50);
}

function fpRenderSidebar(){
  const list = document.getElementById('fp-sidebar-list');
  let html = '';
  for(let i = 0; i < FP_SCENARIOS.length; i++){
    let cls = 'fp-side-item';
    if(i === fpPos) cls += ' fp-current';
    if(fpResults[i] === 'correct') cls += ' fp-correct';
    if(fpResults[i] === 'missed') cls += ' fp-missed';
    let mark = '';
    if(fpResults[i] === 'correct') mark = '<span class="fp-mark">&#10003;</span>';
    else if(fpResults[i] === 'missed') mark = '<span class="fp-mark">&#10007;</span>';
    else if(i === fpPos) mark = '<span class="fp-mark">&#9654;</span>';
    html += '<li class="' + cls + '" onclick="fpJumpTo(' + i + ')"><span class="fp-num">' + (i+1) + '</span>' + mark + '</li>';
  }
  list.innerHTML = html;
}

function fpJumpTo(i){
  if(i < 0 || i >= FP_SCENARIOS.length) return;
  fpPos = i;
  fpRender();
  window.scrollTo(0,0);
}

function fpRender(){
  if(fpPos >= FP_SCENARIOS.length){ fpRenderDone(); return; }
  const s = FP_SCENARIOS[fpPos];
  document.getElementById('fp-progress').textContent = 'Scenario ' + (fpPos+1) + ' of ' + FP_SCENARIOS.length;
  const tierChipClass = 't-' + s.tier;
  const tierLabel = FP_TIER_NAMES[s.tier] || s.tier;
  let html = '<div class="try-card" id="fp-card">';
  html += '<div style="text-align:center"><span class="fp-tier-chip ' + tierChipClass + '">' + tierLabel + '</span></div>';
  html += '<p class="try-scene">' + s.scene + '</p>';
  if(s.setup) html += '<div class="try-setup">' + s.setup + '</div>';
  html += '<p class="try-prompt">' + s.prompt + '</p>';
  html += '<div class="try-opts" id="fp-opts">';
  const keys = ['A','B','C','D'];
  s.options.forEach((o,i) => {
    html += '<button class="try-opt" data-i="' + i + '" data-correct="' + (o.ok ? 'true':'false') + '" onclick="fpAnswer(' + i + ')">';
    html += '<span class="try-key">' + keys[i] + '</span>';
    html += '<span class="try-body">';
    html += '<span class="try-t">' + o.t + '</span>';
    html += '<span class="try-why">' + o.why + '</span>';
    html += '</span></button>';
  });
  html += '</div>';
  html += '<div class="try-takeaway"><b>Takeaway</b>' + s.takeaway + '</div>';
  html += '</div>';
  document.getElementById('fp-body').innerHTML = html;
  document.getElementById('fp-prev').disabled = (fpPos === 0);
  document.getElementById('fp-next').disabled = (fpResults[fpPos] === null);
  document.getElementById('fp-next').innerHTML = (fpPos === FP_SCENARIOS.length - 1) ? 'See Summary &rarr;' : 'Next Scenario &rarr;';
  // Restore answered state if this scenario was already answered
  if(fpResults[fpPos] !== null){
    const card = document.getElementById('fp-card');
    card.classList.add('answered');
    const correctBtn = document.querySelector('#fp-opts .try-opt[data-correct="true"]');
    const pickedBtn = document.querySelector('#fp-opts .try-opt[data-i="' + fpPicked[fpPos] + '"]');
    document.querySelectorAll('#fp-opts .try-opt').forEach(b => b.classList.add('locked'));
    correctBtn.classList.add('correct');
    if(pickedBtn && pickedBtn !== correctBtn) pickedBtn.classList.add('wrongpick');
    document.querySelectorAll('#fp-opts .try-opt').forEach(b => {
      if(b !== correctBtn && b !== pickedBtn) b.classList.add('dim');
    });
    lpVerdict(document.getElementById('fp-opts'), pickedBtn, correctBtn);
  }
  fpRenderSidebar();
}

function fpAnswer(i){
  const card = document.getElementById('fp-card');
  if(card.classList.contains('answered')) return;
  card.classList.add('answered');
  const opts = document.querySelectorAll('#fp-opts .try-opt');
  const correctBtn = document.querySelector('#fp-opts .try-opt[data-correct="true"]');
  opts.forEach(b => b.classList.add('locked'));
  correctBtn.classList.add('correct');
  const clickedBtn = document.querySelector('#fp-opts .try-opt[data-i="' + i + '"]');
  const isCorrect = (clickedBtn === correctBtn);
  if(!isCorrect) clickedBtn.classList.add('wrongpick');
  opts.forEach(b => {
    if(b !== correctBtn && b !== clickedBtn) b.classList.add('dim');
  });
  lpVerdict(document.getElementById('fp-opts'), clickedBtn, correctBtn);
  fpResults[fpPos] = isCorrect ? 'correct' : 'missed';
  fpPicked[fpPos] = i;
  document.getElementById('fp-next').disabled = false;
  fpRenderSidebar();
}

function fpNext(){
  if(fpPos < FP_SCENARIOS.length - 1){
    fpPos++; fpRender(); window.scrollTo(0,0);
  } else {
    fpPos = FP_SCENARIOS.length;
    fpRenderDone();
  }
}

function fpPrev(){
  if(fpPos > 0){ fpPos--; fpRender(); window.scrollTo(0,0); }
}

